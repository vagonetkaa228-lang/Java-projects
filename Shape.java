package practicum_5;


public abstract class Shape implements Comparable<Shape> {
    protected String name;

    public Shape(String name) {
        this.name = name;
    }

    // Абстрактный метод — каждый наследник обязан реализовать по-своему
    public abstract double area();

    // Обычный метод — общий для всех, использует абстрактный
    public String describe() {
        return name + ", area = " + area();
    }

    @Override
    public int compareTo(Shape other) {
        return Double.compare(this.area(), other.area());
    }
}


//Абстрактный класс Shape задает общий контракт для всех фигур.
// Он говорит: "Любая фигура обязана иметь имя и уметь считать площадь".
// Но он не знает, как именно её считать, поэтому метод area() объявлен абстрактным
// — конкретную формулу пишут наследники (Circle и Rectangle).
// Это позволяет нам работать с разными фигурами через общий тип и не плодить дублирующийся код.

//Интерфейс Comparable дает фигурам умение сравниваться.
// Мы реализовали его в базовом классе по площади, чтобы Java понимала, какая фигура "меньше",
